def get_translator(lang):
    """Returns a t(key, **kwargs) function bound to the given language."""
    table = TR.get(lang, TR[DEFAULT_LANG])
    fallback = TR[DEFAULT_LANG]

    def t(key, **kwargs):
        text = table.get(key, fallback.get(key, key))
        if kwargs:
            try:
                return text.format(**kwargs)
            except (KeyError, IndexError):
                return text
        return text

    return t